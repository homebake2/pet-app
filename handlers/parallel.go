package handlers

import "sync"

// runParallel выполняет независимые шаги одновременно и возвращается, когда
// завершились все. Шаги читают данные из БД (каждый запрос берёт своё
// соединение из пула), поэтому время ответа равно самому долгому шагу, а не
// сумме: задержка сети до базы — основная часть времени запроса. Шаг
// сохраняет результат и ошибку в переменные вызывающего; ошибки вызывающий
// проверяет после возврата в нужном ему порядке. Шаги не должны писать в
// http.ResponseWriter, кроме одного, который вызывающий считает «главным» и
// проверяет первым. Паника шага передаётся вызывающему: паника в отдельной
// горутине иначе завершила бы весь процесс мимо перехватчика Sentry.
func runParallel(steps ...func()) {
	var wg sync.WaitGroup
	panics := make([]any, len(steps))
	wg.Add(len(steps))
	for i, step := range steps {
		go func() {
			defer wg.Done()
			defer func() {
				panics[i] = recover()
			}()
			step()
		}()
	}
	wg.Wait()
	for _, p := range panics {
		if p != nil {
			panic(p)
		}
	}
}
